-- First player-owned modules for tennis training and tournament tracking.
-- Existing official equipment/stringing tables are intentionally unchanged.

begin;

create table if not exists public.tennis_training_sessions (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  training_date date not null default current_date,
  duration_minutes integer check (duration_minutes is null or duration_minutes between 1 and 1440),
  session_type text not null default 'technical'
    check (session_type in ('technical', 'tactical', 'match_play', 'serve', 'fitness', 'other')),
  focus text,
  intensity smallint check (intensity is null or intensity between 1 and 10),
  location text,
  notes text,
  created_at timestamptz not null default now(),
  constraint tennis_training_sessions_user_id_id_key unique (user_id, id)
);

create table if not exists public.tournaments (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name text not null check (length(btrim(name)) between 1 and 160),
  start_date date not null,
  end_date date,
  location text,
  surface text check (surface is null or surface in ('hard', 'clay', 'grass', 'carpet', 'other')),
  category text,
  notes text,
  created_at timestamptz not null default now(),
  constraint tournaments_date_order check (end_date is null or end_date >= start_date),
  constraint tournaments_user_id_id_key unique (user_id, id)
);

create table if not exists public.tournament_matches (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  tournament_id bigint not null,
  match_date date,
  round text,
  opponent text not null check (length(btrim(opponent)) between 1 and 160),
  outcome text not null check (outcome in ('win', 'loss', 'retired', 'walkover')),
  score text,
  notes text,
  created_at timestamptz not null default now(),
  constraint tournament_matches_tournament_owner_fk
    foreign key (user_id, tournament_id) references public.tournaments (user_id, id) on delete cascade
);

create index if not exists tennis_training_sessions_owner_date_idx
  on public.tennis_training_sessions (user_id, training_date desc);
create index if not exists tournaments_owner_date_idx
  on public.tournaments (user_id, start_date desc);
create index if not exists tournament_matches_owner_tournament_idx
  on public.tournament_matches (user_id, tournament_id, match_date desc);

grant select, insert, update, delete on
  public.tennis_training_sessions,
  public.tournaments,
  public.tournament_matches
to authenticated;
grant usage, select on sequence
  public.tennis_training_sessions_id_seq,
  public.tournaments_id_seq,
  public.tournament_matches_id_seq
to authenticated;

do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'tennis_training_sessions', 'tournaments', 'tournament_matches'
  ] loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('drop policy if exists %I on public.%I', table_name || '_owner_guard', table_name);
    execute format(
      'create policy %I on public.%I as restrictive for all to public using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()))',
      table_name || '_owner_guard', table_name
    );
    execute format('drop policy if exists %I on public.%I', table_name || '_owner_access', table_name);
    execute format(
      'create policy %I on public.%I for all to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()))',
      table_name || '_owner_access', table_name
    );
  end loop;
end;
$$;

commit;
